"""Exact certificate for theory/COMPLETION_PROOF.md.

Counts locks and open rows, checks the rational identities, the clock
quotients, and the baseline hash. Writes nothing.
"""

from __future__ import annotations

import hashlib
import json
from fractions import Fraction
from pathlib import Path

THEORY = Path(__file__).resolve().parent
ROOT = THEORY.parents[1] / "falsifier"
import sys

sys.path.insert(0, str(ROOT))
from content_sha import WORK_BASELINE_SHA, content_sha256

BASELINE_SHA = WORK_BASELINE_SHA
OPEN_EXTRAS = (
    "color",
    "occupancy",
    "tau",
    "hop-case",
    "k",
    "L",
    "y",
    "GeV",
    "M_R",
    "metric",
    "A",
    "c2",
    "fibration_class",
    "EOM",
    "G_N",
)
PASSED: list[str] = []


def check(name: str, ok: bool, detail: str = "") -> None:
    if not ok:
        raise SystemExit(f"FAIL {name}" + (f": {detail}" if detail else ""))
    PASSED.append(name)


def quotient_order(modulus: int, step: int) -> int:
    seen = {0}
    x = 0
    for _ in range(modulus):
        x = (x + step) % modulus
        if x in seen:
            break
        seen.add(x)
    return modulus // len(seen)


def main() -> int:
    kappa = Fraction(9, 16)
    check("4 kappa = 9/4", 4 * kappa == Fraction(9, 4))
    check("4 kappa + 1 = 13/4", 4 * kappa + 1 == Fraction(13, 4))
    check("banned swap is false", 4 * kappa + 1 != Fraction(9, 4))

    # tau = a + b sqrt(2). Mass coefficient (3/16)*n*tau, compared by parts.
    taus = ((2, -1), (3, 0), (2, 1))
    image = []
    for n in (3, 8, 15):
        for a, b in taus:
            image.append((Fraction(3 * n * a, 16), Fraction(3 * n * b, 16)))
    check("nine hop products", len(image) == 9 and len(set(image)) == 9)
    check("zero branch is outside the nine", (Fraction(0), Fraction(0)) not in image)
    # (2 ± sqrt(2))^2 = 6 ± 4 sqrt(2) equals 3/4 only if 441 = 512.
    check("tau squares are not sigma squared", 441 != 512)

    check("clock face +8 has order 3", quotient_order(24, 8) == 8 and 24 // 8 == 3)
    # <8> = {0,8,16}, order 3, quotient order 8.
    face = {0}
    x = 0
    while True:
        x = (x + 8) % 24
        if x in face:
            break
        face.add(x)
    check("subgroup generated by 8 has order 3", face == {0, 8, 16})
    order8 = { (3 * k) % 24 for k in range(8) }
    check("unique order-8 subgroup has index 3", order8 == {0, 3, 6, 9, 12, 15, 18, 21} and 24 // 8 == 3)

    isolate = json.loads((ROOT / "isolate_updated.json").read_text(encoding="utf-8"))
    locks = [item for item in isolate["locks"] if item.get("status") == "LOCK"]
    check("35 locks", len(locks) == 35, str(len(locks)))
    check("every lock has extras 0", all(item.get("extras") == 0 for item in locks))
    by_name = {item["name"]: item for item in locks}
    knob = by_name["continuous_knobs"]
    check("continuous_knobs is 0", knob.get("value") == 0 and knob.get("extras") == 0)
    maps = [item for item in isolate["maps"] if item.get("status") == "MAP"]
    check("twelve map rows", len(maps) == 12, str(len(maps)))

    translation = (THEORY / "TRANSLATION.md").read_text(encoding="utf-8")
    missing = [name for name in ("color letter", "occupancy", "GeV", "G_{\\mathrm{eff}}", "observed face", "fibration") if name not in translation]
    check("translation page carries the speech", not missing, str(missing))
    check("fifteen sound names are the stated list", len(OPEN_EXTRAS) == 15)

    digest = content_sha256(ROOT / "complete_baseline.json")
    check("baseline hash unchanged", digest == BASELINE_SHA, digest)

    print("COMPLETION PROOF CERTIFICATE PASS")
    print(f"lemmas {len(PASSED)}")
    for name in PASSED:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
