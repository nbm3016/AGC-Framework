def write_report(payload: Dict[str, Any]) -> None:
    lines = [
        "# Layer A consolidation",
        "",
        "CONSOLIDATE LAYER A - GENERATOR STILL ON - ZERO KNOBS",
        "",
        f"Algebra remains `{payload['algebra']}`. Spectral dimension remains `{payload['spectral_dimension']}`. "
        f"Cone holonomy remains `{payload['hol_as_holonomy']}` as holonomy. "
        f"That holonomy is color: {payload['hol_is_color']}.",
        "",
        f"Already generated: {payload['n_already']}. Newly generated: {payload['n_new']}. "
        "The isolate is not frozen. `continuous_knobs = 0`.",
        "",
        "## Already generated",
        "",
        "| name | live_bin | value |",
        "|------|----------|-------|",
    ]
    for row in payload["already"]:
        lines.append(f"| {row['name']} | {row['live_bin']} | {row['value']} |")
    lines += [
        "",
        "## Newly generated",
        "",
        "| extra_names | unique? | live_bin | why |",
        "|-------------|---------|----------|-----|",
    ]
    for row in payload["new"]:
        uniq = "Yes" if row["unique"] else "No"
        why = row["why"].replace("|", "/")
        lines.append(f"| {', '.join(row['extra_names'])} | {uniq} | {row['live_bin']} | {why} |")
    lines += ["", "## G2–G5", ""]
    for row in payload["G"]:
        gates = ", ".join(row.get("gates") or []) or "—"
        why = "; ".join(row.get("reasons") or [])
        lines.append(f"- **{row['id']}** {row['text']} Answer: {row['answer']}. Bin `{row['bin']}`. Gates: {gates}. {why}")
    lines += [
        "",
        f"`g_mu_nu` stays `{payload['g_mu_nu_type']}` with `value_forced = {payload['g_mu_nu_value_forced']}`. "
        f"Unique color stays `{payload['unique_color']}`.",
        "",
        "Layer A is not frozen.",
        "",
    ]
    with open(REPORT_PATH, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


