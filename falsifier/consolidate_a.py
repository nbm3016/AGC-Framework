def fail(msg: str) -> None:
    print("FAIL CLOSED:", msg, file=sys.stderr)
    raise SystemExit(1)


def load_json(path: str) -> Dict[str, Any]:
    if not os.path.isfile(path):
        fail(f"missing {path}")
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def sphere_betti(dim: int, degree: int) -> int:
    if degree < 0 or degree > dim:
        return 0
    return 1 if degree in (0, dim) else 0


def product_betti(dim_a: int, dim_b: int, degree: int) -> int:
    return sum(sphere_betti(dim_a, i) * sphere_betti(dim_b, degree - i) for i in range(degree + 1))


def spectrum_keys_on_disk() -> List[str]:
    """Cutoff-free D5 eigenvalue list, if a file already stores one."""
    hits: List[str] = []
    needles = ("d5_spectrum", "dirac_eigenvalues", "eigenvalues_d5")
    skip = {".git", "mcps", "agent-tools", "__pycache__", "terminals", ".grok"}
    for dirpath, dirnames, filenames in os.walk(ARTIFACT_DIR):
        dirnames[:] = [d for d in dirnames if d not in skip]
        for name in filenames:
            if not name.endswith(".json"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), ARTIFACT_DIR)
            if rel in {"generated_inventory.json"}:
                continue
            try:
                with open(os.path.join(dirpath, name), encoding="utf-8") as handle:
                    blob = handle.read().lower()
            except OSError:
                continue
            if any(needle in blob for needle in needles):
                hits.append(rel)
    return hits


def killing_tower(link_dim: int) -> List[str]:
    """Forms generated by the contact form and its exterior derivative on an SE link."""
    transverse_dim = link_dim - 1
    max_power = transverse_dim // 2
    names: List[str] = []
    for power in range(0, max_power + 1):
        names.append("eta" if power == 0 else f"eta_wedge_(d eta)^{power}")
        if power >= 1:
            names.append(f"(d eta)^{power}")
    return names


