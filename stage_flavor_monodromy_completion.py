def update_expansion_state(res: Dict[str, Any]) -> None:
    if not os.path.isfile(EXPANSION_STATE_PATH):
        return
    es = load_json(EXPANSION_STATE_PATH)
    ts = res["timestamp_utc"]
    es["continuous_knobs"] = 0
    es["flavor_monodromy_completion"] = {
        "status": "partial_a4_nlo_no_further_completion",
        "further_completion_forced": False,
        "official_angles_unchanged": True,
        "a4_preferred_not_unique": True,
        "file": "flavor_monodromy_completion.json",
        "timestamp_utc": ts,
    }
    es.setdefault("scaffolding_log", []).append(
        {
            "cycle": "flavor_monodromy_completion",
            "action": "inventory_plus_completion_veto",
            "item": "A4 + locked NLO; no further discrete completion forced",
            "status": "partial_theorem",
            "timestamp_utc": ts,
        }
    )
    es["last_updated"] = ts
    with open(EXPANSION_STATE_PATH, "w", encoding="utf-8") as f:
        json.dump(es, f, indent=2)
        f.write("\n")


