def load_json(path: str) -> Dict[str, Any]:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def phase_order(n: int, period: int = CYCLOTOMIC_PERIOD) -> int:
    """Order of exp(i n π/12) = exp(2π i n/24) on the unit circle."""
    g = gcd(n, period)
    return period // g


